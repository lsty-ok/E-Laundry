function isoDaysAgo(daysAgo: number, hour: number = 10, minute: number = 15): string {
  const d = new Date('2026-11-23T12:00:00+07:00');
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

